        for d in /etc/wireguard/wg0 /etc/wireguard/abslink; do
            [[ -f "$d/brain_url" ]] && BRAIN_URL=$(cat "$d/brain_url") && break
        done
    fi
    [[ -n "$BRAIN_URL" ]] || { echo "Usage: $0 rotate-secret [BRAIN_URL]"; exit 1; }
elif [[ "$SUBCMD" == "list-networks" ]]; then
