    # `enroll` writes this; `update` on an existing install without it
    # didn't — so write it here so the -b upgrade converges cleanly.
    # Watchdog kickstarts io.wg0.heartbeat every 120s if its log is stale.
    if [[ -f "$HB_WATCHDOG_PLIST" ]]; then
        launchctl unload "$HB_WATCHDOG_PLIST" 2>/dev/null || true
    fi
    cat > "$HB_WATCHDOG_PLIST" <<HBWPLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>io.wg0.heartbeat-watchdog</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>-c</string>
        <string>LOG=/var/log/wg0-heartbeat.log; STALE=120; if [[ ! -f "\$LOG" ]] || (( \$(date +%s) - \$(stat -f %m "\$LOG" 2>/dev/null || echo 0) > STALE )); then launchctl kickstart -k system/io.wg0.heartbeat 2>/dev/null || launchctl load ${LAUNCHDAEMON_PLIST} 2>/dev/null; echo "[\$(date -u +%H:%M:%SZ)] watchdog: kicked heartbeat (stale >\${STALE}s)" >> /var/log/wg0-heartbeat-watchdog.log; fi</string>
    </array>
    <key>StartInterval</key>
    <integer>120</integer>
    <key>RunAtLoad</key>
    <true/>
    <key>StandardErrorPath</key>
    <string>/var/log/wg0-heartbeat-watchdog.log</string>
    <key>StandardOutPath</key>
    <string>/var/log/wg0-heartbeat-watchdog.log</string>
</dict>
</plist>
HBWPLIST
    if launchctl load "$HB_WATCHDOG_PLIST" 2>/dev/null; then
        log "Heartbeat watchdog installed/refreshed (io.wg0.heartbeat-watchdog)"
    else
        warn "launchctl load of heartbeat watchdog failed — stalls will not self-heal"
    fi

    # ── Network-state watcher (roaming) — idempotent install/refresh ────────
    # Listens to BSD route(4) for interface/address transitions and forces
    # an immediate heartbeat on each change. Without this, a Wi-Fi → Ethernet
    # or work-LAN → home-LAN handoff sat in a degraded state for up to 30s
    # (next periodic heartbeat) before the brain saw the new endpoint and
    # the connector pulled fresh peer state. With this, convergence is sub-
    # second: the moment route(4) reports a path change we kickstart the
    # heartbeat, which re-registers the new public endpoint and pulls any
    # relay-mode flips the brain decided on.
    write_netmon_script
    if [[ -f "$NETMON_PLIST" ]]; then
        launchctl unload "$NETMON_PLIST" 2>/dev/null || true
    fi
    cat > "$NETMON_PLIST" <<NETMONPLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>io.wg0.netmon</string>
    <key>ProgramArguments</key>
    <array>
        <string>${NETMON_SCRIPT}</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>ThrottleInterval</key>
    <integer>10</integer>
    <key>StandardErrorPath</key>
    <string>/var/log/wg0-netmon.log</string>
    <key>StandardOutPath</key>
    <string>/var/log/wg0-netmon.log</string>
</dict>
</plist>
NETMONPLIST
    if launchctl load "$NETMON_PLIST" 2>/dev/null; then
        log "Network-state watcher installed/refreshed (io.wg0.netmon)"
    else
        warn "launchctl load of netmon failed — roaming will fall back to 30s heartbeat cadence"
    fi

    # ── 6. Migrate legacy postup/predown scripts ────────────────────────────
    for pair in "abslink-postup:wg0-postup" "abslink-predown:wg0-predown"; do
        old="/usr/local/bin/${pair%%:*}"
        new="/usr/local/bin/${pair##*:}"
        if [[ -f "$old" && "$old" != "$new" ]]; then
            mv "$old" "$new"
        fi
    done
    # Update PostUp/PreDown references in WireGuard config
    if [[ -f "$WG_CONF" ]]; then
        sed -i '' 's|abslink-postup|wg0-postup|g; s|abslink-predown|wg0-predown|g' "$WG_CONF"
    fi

    # ── 7. Install/update wg0 CLI ────────────────────────────────────────────
    if curl -fsSL "${BRAIN_URL%/api*}/wg0-status.sh" -o /usr/local/bin/wg0 2>/dev/null \
       || curl -fsSL "https://wg0.io/wg0-status.sh" -o /usr/local/bin/wg0 2>/dev/null; then
        chmod +x /usr/local/bin/wg0
        log "Updated wg0 CLI tool"
    fi
    # Remove old abslink CLI if present
    rm -f /usr/local/bin/abslink 2>/dev/null || true

    # ── 8. Force an immediate heartbeat to verify ────────────────────────────
    log "Running heartbeat to verify connectivity..."
    if WG0_HEARTBEAT_STRICT=1 bash "$HEARTBEAT_SCRIPT" 2>/dev/null; then
        log "Heartbeat succeeded — connected to ${BRAIN_URL}"
    else
        warn "Heartbeat failed — check that ${BRAIN_URL} is reachable"
    fi

    log ""
    log "Update complete."
    log "  Brain URL:  ${BRAIN_URL}"
    log "  Node ID:    ${NODE_ID}"
    log "  Key dir:    ${KEY_DIR}"
    log ""
    log "Run 'wg0 status' to verify tunnel health."
    exit 0
fi

